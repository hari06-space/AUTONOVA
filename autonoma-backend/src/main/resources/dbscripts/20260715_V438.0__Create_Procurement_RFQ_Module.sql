-- 1. Procurement Settings
IF NOT EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[PP_PROCUREMENT_SETTINGS]') AND type in (N'U'))
BEGIN
    CREATE TABLE [dbo].[PP_PROCUREMENT_SETTINGS] (
        [ID] BIGINT IDENTITY(1,1) NOT NULL,
        [DIVISION] BIGINT NOT NULL,
        [WEIGHT_PRICE] NUMERIC(5,2) NOT NULL DEFAULT 40.00,
        [WEIGHT_DELIVERY] NUMERIC(5,2) NOT NULL DEFAULT 20.00,
        [WEIGHT_RATING] NUMERIC(5,2) NOT NULL DEFAULT 15.00,
        [WEIGHT_WARRANTY] NUMERIC(5,2) NOT NULL DEFAULT 10.00,
        [WEIGHT_PAYMENT] NUMERIC(5,2) NOT NULL DEFAULT 15.00,
        [CREATED_BY] NVARCHAR(50) NOT NULL,
        [CREATED_DATE] DATETIME NOT NULL DEFAULT GETDATE(),
        [UPDATED_BY] NVARCHAR(50) NULL,
        [UPDATED_DATE] DATETIME NULL,
        CONSTRAINT [PK_PP_PROCUREMENT_SETTINGS] PRIMARY KEY CLUSTERED ([ID]),
        CONSTRAINT [FK_PP_PROC_SETTING_DIV] FOREIGN KEY ([DIVISION]) REFERENCES [dbo].[AD_DIVISION]([ID])
    );
END
