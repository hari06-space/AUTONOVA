        CONSTRAINT [FK_PP_RFQ_HEAD_PR] FOREIGN KEY ([PR_REF_ID]) REFERENCES [dbo].[PP_PURCHASE_REQUEST_HEAD]([ID]),
        CONSTRAINT [FK_PP_RFQ_HEAD_DEPT] FOREIGN KEY ([DEPARTMENT_ID]) REFERENCES [dbo].[HR_DEPARTMENT]([ID]),
