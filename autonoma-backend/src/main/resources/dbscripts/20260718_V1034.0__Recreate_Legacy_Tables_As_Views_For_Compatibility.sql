SELECT 6 AS LEAVE_TYPE_ID, 'LOP' AS LEAVE_CODE, 'Loss of Pay' AS LEAVE_NAME, 'Loss of Pay' AS DESCRIPTION, CAST(1 AS BIT) AS IS_ACTIVE, 'SYSTEM' AS CREATED_BY, GETDATE() AS CREATED_DATE, NULL AS UPDATED_BY, NULL AS UPDATED_DATE
