SELECT 7 AS LEAVE_TYPE_ID, 'WFH' AS LEAVE_CODE, 'Work From Home' AS LEAVE_NAME, 'Work From Home' AS DESCRIPTION, CAST(1 AS BIT) AS IS_ACTIVE, 'SYSTEM' AS CREATED_BY, GETDATE() AS CREATED_DATE, NULL AS UPDATED_BY, NULL AS UPDATED_DATE;
GO
