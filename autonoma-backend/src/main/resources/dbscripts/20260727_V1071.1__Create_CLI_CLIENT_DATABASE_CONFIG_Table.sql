        ALTER TABLE CLI_CLIENT_DATABASE_CONFIG ADD DB_TYPE NVARCHAR(50) DEFAULT 'Microsoft SQL Server';
    IF NOT EXISTS (SELECT * FROM sys.columns WHERE object_id = OBJECT_ID('CLI_CLIENT_DATABASE_CONFIG') AND name = 'DB_HOST')
        ALTER TABLE CLI_CLIENT_DATABASE_CONFIG ADD DB_HOST NVARCHAR(150) NULL;
