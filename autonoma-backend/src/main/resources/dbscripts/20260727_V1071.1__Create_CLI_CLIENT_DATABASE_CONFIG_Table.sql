IF NOT EXISTS (SELECT * FROM sys.tables WHERE name = 'CLI_CLIENT_DATABASE_CONFIG')
BEGIN
    CREATE TABLE CLI_CLIENT_DATABASE_CONFIG (
        ID BIGINT IDENTITY(1,1) PRIMARY KEY,
        CLIENT_ID BIGINT NOT NULL,
        CLIENT_CODE NVARCHAR(10) NOT NULL,
        DB_TYPE NVARCHAR(50) DEFAULT 'Microsoft SQL Server',
        DB_HOST NVARCHAR(150) NULL,
        DB_PORT INT DEFAULT 1433,
        DB_NAME NVARCHAR(150) NULL,
        DB_USERNAME NVARCHAR(100) NULL,
        DB_PASSWORD NVARCHAR(500) NULL,
        CREATED_BY NVARCHAR(50) NULL,
        UPDATED_BY NVARCHAR(50) NULL,
        CREATED_AT DATETIME2 DEFAULT GETDATE(),
        UPDATED_AT DATETIME2 DEFAULT GETDATE(),
        CONSTRAINT FK_CLI_DB_CLIENT_ID FOREIGN KEY (CLIENT_ID) REFERENCES CLI_CLIENT_MASTER(ID) ON DELETE CASCADE
    );

    CREATE INDEX IDX_CLI_DB_CLIENT_ID ON CLI_CLIENT_DATABASE_CONFIG(CLIENT_ID);
    CREATE INDEX IDX_CLI_DB_CLIENT_CODE ON CLI_CLIENT_DATABASE_CONFIG(CLIENT_CODE);
END;
ELSE
BEGIN
