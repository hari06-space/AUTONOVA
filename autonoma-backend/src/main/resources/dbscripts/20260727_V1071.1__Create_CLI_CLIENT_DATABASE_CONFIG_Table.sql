        ALTER TABLE CLI_CLIENT_DATABASE_CONFIG ADD DB_PORT INT DEFAULT 1433;
    IF NOT EXISTS (SELECT * FROM sys.columns WHERE object_id = OBJECT_ID('CLI_CLIENT_DATABASE_CONFIG') AND name = 'DB_NAME')
        ALTER TABLE CLI_CLIENT_DATABASE_CONFIG ADD DB_NAME NVARCHAR(150) NULL;
    IF NOT EXISTS (SELECT * FROM sys.columns WHERE object_id = OBJECT_ID('CLI_CLIENT_DATABASE_CONFIG') AND name = 'DB_USERNAME')
        ALTER TABLE CLI_CLIENT_DATABASE_CONFIG ADD DB_USERNAME NVARCHAR(100) NULL;
