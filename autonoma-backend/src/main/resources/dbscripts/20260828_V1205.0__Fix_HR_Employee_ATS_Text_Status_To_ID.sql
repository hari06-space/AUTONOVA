-- ============================================================================
-- V1205.0 - Fix HR_EMPLOYEE ATS Status Columns (Proper Flow Mapping)
-- 
-- ATS Valid Flow: PENDING → SENT → TO BE VERIFY → VERIFIED → REJECTED
--
-- Problem:
--   Migrated HR_EMPLOYEE records have legacy text or out-of-flow status values
--   (e.g., 'SUBMITTED', 'DRAFT', 'IN_PROGRESS', 'APPROVED', 'CONFIRM',
--    'CANCELLED', 'EXPIRED') which break the current ATS workflow and cause:
--     java.lang.NumberFormatException: For input string: "SUBMITTED"
--     SQLServerException: An error occurred while converting the nvarchar value
--                         to JDBC data type BIGINT.
--   Also, PHOTO/RESUME/PAYSLIP/AADHAR_VERIFIED_STATUS were NVARCHAR(50) instead
--   of BIGINT, mismatching the JPA @ManyToOne FK mapping.
--
-- Solution:
--   1. Ensure ONLY valid ATS flow statuses exist (Pending, SENT, TO BE VERIFY,
--      Verified, Rejected). Do NOT add SUBMITTED/DRAFT/IN_PROGRESS etc.
--   2. Remap text status values to nearest valid flow equivalent.
--   3. Remap numeric IDs for out-of-flow statuses to valid flow IDs.
--   4. ALTER nvarchar verified-status columns to BIGINT.
--   5. Add FK constraints.
-- ============================================================================

-- Step 1: Ensure ONLY valid ATS flow statuses exist in AD_STATUS_MASTER
BEGIN TRY IF NOT EXISTS (SELECT 1 FROM AD_STATUS_MASTER WHERE UPPER(TRIM(NAME)) = 'PENDING')    INSERT INTO AD_STATUS_MASTER (NAME) VALUES ('Pending');    END TRY BEGIN CATCH END CATCH;
BEGIN TRY IF NOT EXISTS (SELECT 1 FROM AD_STATUS_MASTER WHERE UPPER(TRIM(NAME)) = 'SENT')       INSERT INTO AD_STATUS_MASTER (NAME) VALUES ('SENT');       END TRY BEGIN CATCH END CATCH;
BEGIN TRY IF NOT EXISTS (SELECT 1 FROM AD_STATUS_MASTER WHERE UPPER(TRIM(NAME)) = 'TO BE VERIFY') INSERT INTO AD_STATUS_MASTER (NAME) VALUES ('TO BE VERIFY'); END TRY BEGIN CATCH END CATCH;
BEGIN TRY IF NOT EXISTS (SELECT 1 FROM AD_STATUS_MASTER WHERE UPPER(TRIM(NAME)) = 'VERIFIED')   INSERT INTO AD_STATUS_MASTER (NAME) VALUES ('Verified');   END TRY BEGIN CATCH END CATCH;
BEGIN TRY IF NOT EXISTS (SELECT 1 FROM AD_STATUS_MASTER WHERE UPPER(TRIM(NAME)) = 'REJECTED')   INSERT INTO AD_STATUS_MASTER (NAME) VALUES ('Rejected');   END TRY BEGIN CATCH END CATCH;
GO

-- Step 2: Remap text status values in all status columns to valid ATS flow IDs
-- Mapping logic:
--   SUBMITTED    -> TO BE VERIFY  (submitted = awaiting verification, closest fit)
--   DRAFT        -> Pending       (not started)
--   IN_PROGRESS  -> Pending       (still pending)
--   APPROVED     -> Verified      (approved = verified)
--   CONFIRM      -> TO BE VERIFY  (confirm = needs verification)
--   TO BE VERIFIED -> TO BE VERIFY (canonical rename)
--   CANCELLED    -> Rejected      (cancelled = rejected)
--   EXPIRED      -> Rejected      (expired = rejected)
--   Others       -> match by name if possible, else leave (will be caught by Step 3)

DECLARE @remapByName NVARCHAR(MAX);
SET @remapByName = '
UPDATE e SET e.{col} = (
    SELECT TOP 1 s2.ID FROM AD_STATUS_MASTER s2 WHERE s2.NAME =
    CASE UPPER(TRIM(CAST(e.{col} AS VARCHAR(100))))
        WHEN ''SUBMITTED''     THEN ''TO BE VERIFY''
        WHEN ''DRAFT''         THEN ''Pending''
        WHEN ''IN_PROGRESS''   THEN ''Pending''
        WHEN ''APPROVED''      THEN ''Verified''
        WHEN ''CONFIRM''       THEN ''TO BE VERIFY''
        WHEN ''TO BE VERIFIED'' THEN ''TO BE VERIFY''
        WHEN ''CANCELLED''     THEN ''Rejected''
        WHEN ''EXPIRED''       THEN ''Rejected''
        ELSE NULL
    END
)
FROM HR_EMPLOYEE e
WHERE TRY_CAST(e.{col} AS BIGINT) IS NULL AND e.{col} IS NOT NULL
';

BEGIN TRY EXEC(REPLACE(@remapByName, '{col}', 'STATUS'));                       PRINT 'STATUS text remapped'; END TRY BEGIN CATCH PRINT 'Warning STATUS: ' + ERROR_MESSAGE(); END CATCH;
GO
