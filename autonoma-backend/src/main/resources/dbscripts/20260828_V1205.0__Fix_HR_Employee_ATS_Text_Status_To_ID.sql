-- Step 4: Fix nvarchar PHOTO/RESUME/PAYSLIP/AADHAR_VERIFIED_STATUS columns
-- These must be BIGINT to match the JPA @ManyToOne FK mapping

BEGIN TRY
    -- Fix text values first (same mapping)
    UPDATE e SET e.PHOTO_VERIFIED_STATUS = CAST(s.ID AS NVARCHAR(50))
    FROM HR_EMPLOYEE e INNER JOIN AD_STATUS_MASTER s
        ON UPPER(TRIM(s.NAME)) = UPPER(TRIM(e.PHOTO_VERIFIED_STATUS))
    WHERE TRY_CAST(e.PHOTO_VERIFIED_STATUS AS BIGINT) IS NULL AND e.PHOTO_VERIFIED_STATUS IS NOT NULL;

    UPDATE e SET e.RESUME_VERIFIED_STATUS = CAST(s.ID AS NVARCHAR(50))
    FROM HR_EMPLOYEE e INNER JOIN AD_STATUS_MASTER s
        ON UPPER(TRIM(s.NAME)) = UPPER(TRIM(e.RESUME_VERIFIED_STATUS))
    WHERE TRY_CAST(e.RESUME_VERIFIED_STATUS AS BIGINT) IS NULL AND e.RESUME_VERIFIED_STATUS IS NOT NULL;

    UPDATE e SET e.PAYSLIP_VERIFIED_STATUS = CAST(s.ID AS NVARCHAR(50))
    FROM HR_EMPLOYEE e INNER JOIN AD_STATUS_MASTER s
        ON UPPER(TRIM(s.NAME)) = UPPER(TRIM(e.PAYSLIP_VERIFIED_STATUS))
    WHERE TRY_CAST(e.PAYSLIP_VERIFIED_STATUS AS BIGINT) IS NULL AND e.PAYSLIP_VERIFIED_STATUS IS NOT NULL;

    UPDATE e SET e.AADHAR_VERIFIED_STATUS = CAST(s.ID AS NVARCHAR(50))
    FROM HR_EMPLOYEE e INNER JOIN AD_STATUS_MASTER s
