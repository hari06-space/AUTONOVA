-- Step 6: Fix HR_EMPLOYEE_SELF_ASSESSMENT.SELF_ASSESSMENT_STATUS (NVARCHAR -> BIGINT)
-- This column had 'SUBMITTED' text values which caused NumberFormatException.
-- Map: SUBMITTED -> TO BE VERIFY, DRAFT/68 -> Pending

BEGIN TRY
    -- Remap text 'SUBMITTED' -> TO BE VERIFY ID
    UPDATE HR_EMPLOYEE_SELF_ASSESSMENT 
    SET SELF_ASSESSMENT_STATUS = CAST((SELECT TOP 1 ID FROM AD_STATUS_MASTER WHERE NAME = 'TO BE VERIFY') AS NVARCHAR(50))
    WHERE UPPER(TRIM(ISNULL(SELF_ASSESSMENT_STATUS,''))) = 'SUBMITTED';
    PRINT 'SELF_ASSESSMENT: SUBMITTED remapped: ' + CAST(@@ROWCOUNT AS VARCHAR);

    -- Remap other invalid text values
    UPDATE HR_EMPLOYEE_SELF_ASSESSMENT 
    SET SELF_ASSESSMENT_STATUS = CAST((SELECT TOP 1 ID FROM AD_STATUS_MASTER WHERE NAME = 'Pending') AS NVARCHAR(50))
    WHERE UPPER(TRIM(ISNULL(SELF_ASSESSMENT_STATUS,''))) IN ('DRAFT','IN_PROGRESS')
       OR (TRY_CAST(SELF_ASSESSMENT_STATUS AS BIGINT) = (SELECT TOP 1 ID FROM AD_STATUS_MASTER WHERE UPPER(NAME)='DRAFT'));
    PRINT 'SELF_ASSESSMENT: DRAFT remapped: ' + CAST(@@ROWCOUNT AS VARCHAR);

    -- Drop default constraint if exists
    DECLARE @saConstraint NVARCHAR(200);
    SELECT @saConstraint = d.name 
    FROM sys.default_constraints d
    JOIN sys.columns c ON d.parent_object_id = c.object_id AND d.parent_column_id = c.column_id
    WHERE c.object_id = OBJECT_ID('HR_EMPLOYEE_SELF_ASSESSMENT') AND c.name = 'SELF_ASSESSMENT_STATUS';
    IF @saConstraint IS NOT NULL
        EXEC('ALTER TABLE HR_EMPLOYEE_SELF_ASSESSMENT DROP CONSTRAINT ' + @saConstraint);

    -- Drop FK if exists
    IF EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_HR_EMP_SELF_ASSESS_STATUS')
        ALTER TABLE HR_EMPLOYEE_SELF_ASSESSMENT DROP CONSTRAINT FK_HR_EMP_SELF_ASSESS_STATUS;

    -- Alter NVARCHAR -> BIGINT
    IF EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='HR_EMPLOYEE_SELF_ASSESSMENT' AND COLUMN_NAME='SELF_ASSESSMENT_STATUS' AND DATA_TYPE IN ('nvarchar','varchar'))
        ALTER TABLE HR_EMPLOYEE_SELF_ASSESSMENT ALTER COLUMN SELF_ASSESSMENT_STATUS BIGINT NULL;
    PRINT 'SELF_ASSESSMENT_STATUS altered to BIGINT';

    -- Add FK
    IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_HR_EMP_SELF_ASSESS_STATUS')
        ALTER TABLE HR_EMPLOYEE_SELF_ASSESSMENT ADD CONSTRAINT FK_HR_EMP_SELF_ASSESS_STATUS 
        FOREIGN KEY (SELF_ASSESSMENT_STATUS) REFERENCES AD_STATUS_MASTER(ID);
    PRINT 'SELF_ASSESSMENT_STATUS FK added';
END TRY BEGIN CATCH PRINT 'Warning SELF_ASSESSMENT_STATUS: ' + ERROR_MESSAGE(); END CATCH;
GO

