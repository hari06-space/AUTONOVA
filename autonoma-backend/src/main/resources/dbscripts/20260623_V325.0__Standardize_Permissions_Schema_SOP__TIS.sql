SELECT @SqlDropFks += N'ALTER TABLE ' + QUOTENAME(OBJECT_SCHEMA_NAME(parent_object_id)) + '.' + QUOTENAME(OBJECT_NAME(parent_object_id)) + 
               ' DROP CONSTRAINT ' + QUOTENAME(name) + ';' + CHAR(13) + CHAR(10)
FROM sys.foreign_keys
WHERE parent_object_id IN (
    OBJECT_ID('dbo.HR_PERMISSION_ENTRY'), 
    OBJECT_ID('dbo.SC_PERMISSION_REQUEST'),
    OBJECT_ID('dbo.HR_PERMISSION_ENTRY_OLD'),
    OBJECT_ID('dbo.SC_PERMISSION_REQUEST_OLD')
)
   OR referenced_object_id IN (
    OBJECT_ID('dbo.HR_PERMISSION_ENTRY'), 
    OBJECT_ID('dbo.SC_PERMISSION_REQUEST'),
    OBJECT_ID('dbo.HR_PERMISSION_ENTRY_OLD'),
    OBJECT_ID('dbo.SC_PERMISSION_REQUEST_OLD')
);

IF @SqlDropFks <> N''
BEGIN
    EXEC sp_executesql @SqlDropFks;
    PRINT 'Dropped all foreign key constraints for target tables';
END
GO

