-- =========================================================================
-- 8. CLEAN UP ORPHANED AND INVALID FOREIGN KEY VALUES IN NEW TABLES
-- =========================================================================

-- Clean up invalid references to AD_USER_CREDENTIAL(USER_ID)
-- For CREATED_BY / UPDATED_BY: default to 'System' if not existing
UPDATE dbo.HR_PERMISSION_ENTRY SET CREATED_BY = 'System' WHERE CREATED_BY NOT IN (SELECT USER_ID FROM dbo.AD_USER_CREDENTIAL);
UPDATE dbo.HR_PERMISSION_ENTRY SET UPDATED_BY = 'System' WHERE UPDATED_BY IS NOT NULL AND UPDATED_BY NOT IN (SELECT USER_ID FROM dbo.AD_USER_CREDENTIAL);

UPDATE dbo.SC_PERMISSION_REQUEST SET CREATED_BY = 'System' WHERE CREATED_BY NOT IN (SELECT USER_ID FROM dbo.AD_USER_CREDENTIAL);
UPDATE dbo.SC_PERMISSION_REQUEST SET UPDATED_BY = 'System' WHERE UPDATED_BY IS NOT NULL AND UPDATED_BY NOT IN (SELECT USER_ID FROM dbo.AD_USER_CREDENTIAL);

-- For APPROVED_BY, REJECTED_BY, VERIFIED_BY: nullify if not existing (as they are optional null columns)
UPDATE dbo.HR_PERMISSION_ENTRY SET APPROVED_BY = NULL WHERE APPROVED_BY IS NOT NULL AND APPROVED_BY NOT IN (SELECT USER_ID FROM dbo.AD_USER_CREDENTIAL);
UPDATE dbo.HR_PERMISSION_ENTRY SET REJECTED_BY = NULL WHERE REJECTED_BY IS NOT NULL AND REJECTED_BY NOT IN (SELECT USER_ID FROM dbo.AD_USER_CREDENTIAL);
UPDATE dbo.HR_PERMISSION_ENTRY SET VERIFIED_BY = NULL WHERE VERIFIED_BY IS NOT NULL AND VERIFIED_BY NOT IN (SELECT USER_ID FROM dbo.AD_USER_CREDENTIAL);

UPDATE dbo.SC_PERMISSION_REQUEST SET APPROVED_BY = NULL WHERE APPROVED_BY IS NOT NULL AND APPROVED_BY NOT IN (SELECT USER_ID FROM dbo.AD_USER_CREDENTIAL);
UPDATE dbo.SC_PERMISSION_REQUEST SET REJECTED_BY = NULL WHERE REJECTED_BY IS NOT NULL AND REJECTED_BY NOT IN (SELECT USER_ID FROM dbo.AD_USER_CREDENTIAL);
UPDATE dbo.SC_PERMISSION_REQUEST SET VERIFIED_BY = NULL WHERE VERIFIED_BY IS NOT NULL AND VERIFIED_BY NOT IN (SELECT USER_ID FROM dbo.AD_USER_CREDENTIAL);

-- Clean up employee references
DELETE FROM dbo.HR_PERMISSION_ENTRY WHERE EMPLOYEE_ID NOT IN (SELECT ID FROM dbo.HR_EMPLOYEE);
DELETE FROM dbo.SC_PERMISSION_REQUEST WHERE EMPLOYEE_ID NOT IN (SELECT ID FROM dbo.HR_EMPLOYEE);
DELETE FROM dbo.SC_PERMISSION_REQUEST WHERE PERMISSION_ENTRY_ID NOT IN (SELECT ID FROM dbo.HR_PERMISSION_ENTRY);
GO

