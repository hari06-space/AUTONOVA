-- 4. CREATE NEW STRUCTURE FOR HR_PERMISSION_ENTRY (AUDIT COLUMNS AT THE END)
-- =========================================================================

IF OBJECT_ID('dbo.HR_PERMISSION_ENTRY', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.HR_PERMISSION_ENTRY (
        ID BIGINT IDENTITY(1,1) PRIMARY KEY,
        EMPLOYEE_ID BIGINT NOT NULL,
        PERMISSION_DATE DATE NOT NULL,
        FROM_TIME NVARCHAR(50) NOT NULL,
        TO_TIME NVARCHAR(50) NOT NULL,
        ACTUAL_DURATION NVARCHAR(100) NOT NULL,
        CONSIDERED_DURATION DECIMAL(10,2) NOT NULL,
        REASON NVARCHAR(MAX) NULL,
        STATUS NVARCHAR(50) NULL CONSTRAINT DF_HR_PERMISSION_ENTRY_status DEFAULT 'Pending for Verify',
        MONTH NVARCHAR(50) NOT NULL,
        YEAR INT NOT NULL,
        REJECTION_REASON NVARCHAR(MAX) NULL,
        REQUEST_TYPE NVARCHAR(50) NULL,
        EMPLOYEE_CODE NVARCHAR(50) NULL,
        APPROVED_BY NVARCHAR(50) NULL,
        APPROVED_DATE DATETIME NULL,
        REJECTED_BY NVARCHAR(50) NULL,
        REJECTED_DATE DATETIME NULL,
        REJECTION_COMMENT NVARCHAR(MAX) NULL,
        VERIFIED_BY NVARCHAR(50) NULL,
        VERIFIED_DATE DATETIME NULL,
        IS_ACTIVE BIT NOT NULL CONSTRAINT DF_HR_PERMISSION_ENTRY_is_active DEFAULT 1,
        
        -- SOP §3.1 Mandatory Audit Columns grouped contiguously at the very end
        CREATED_BY NVARCHAR(50) NOT NULL,
        CREATED_DATE DATETIME NOT NULL,
        UPDATED_BY NVARCHAR(50) NULL,
        UPDATED_DATE DATETIME NULL
    );
    PRINT 'Created new HR_PERMISSION_ENTRY table with SOP-compliant layout';
END
GO

