-- 4. CLI_CLIENT_HEALTH_LOG
IF EXISTS (SELECT * FROM sys.tables WHERE name = 'CLI_CLIENT_HEALTH_LOG')
BEGIN
    -- Drop old index on CLIENT_CODE if exists
    IF EXISTS (SELECT * FROM sys.indexes WHERE name = 'IDX_CLI_HEALTH_CLIENT_CODE' AND object_id = OBJECT_ID('CLI_CLIENT_HEALTH_LOG'))
    BEGIN
        DROP INDEX IDX_CLI_HEALTH_CLIENT_CODE ON CLI_CLIENT_HEALTH_LOG;
    END

    -- Add CLIENT_ID column if it does not exist
    IF NOT EXISTS (SELECT * FROM sys.columns WHERE object_id = OBJECT_ID('CLI_CLIENT_HEALTH_LOG') AND name = 'CLIENT_ID')
    BEGIN
        ALTER TABLE CLI_CLIENT_HEALTH_LOG ADD CLIENT_ID BIGINT NULL;
        
        -- Populate CLIENT_ID with default company ID from AD_COMPANY_CREDENTIAL
        UPDATE CLI_CLIENT_HEALTH_LOG 
        SET CLIENT_ID = ISNULL((SELECT TOP 1 id FROM AD_COMPANY_CREDENTIAL ORDER BY id ASC), 1)
        WHERE CLIENT_ID IS NULL;

        ALTER TABLE CLI_CLIENT_HEALTH_LOG ALTER COLUMN CLIENT_ID BIGINT NOT NULL;
    END

    -- Add index on CLIENT_ID if not exists
    IF NOT EXISTS (SELECT * FROM sys.indexes WHERE name = 'IDX_CLI_HEALTH_CLIENT_ID' AND object_id = OBJECT_ID('CLI_CLIENT_HEALTH_LOG'))
    BEGIN
        CREATE INDEX IDX_CLI_HEALTH_CLIENT_ID ON CLI_CLIENT_HEALTH_LOG(CLIENT_ID);
    END

    -- Add foreign key referencing AD_COMPANY_CREDENTIAL(id)
    IF NOT EXISTS (SELECT * FROM sys.foreign_keys WHERE name = 'FK_CLI_HEALTH_COMPANY' AND parent_object_id = OBJECT_ID('CLI_CLIENT_HEALTH_LOG'))
    BEGIN
        ALTER TABLE CLI_CLIENT_HEALTH_LOG 
        ADD CONSTRAINT FK_CLI_HEALTH_COMPANY FOREIGN KEY (CLIENT_ID) REFERENCES AD_COMPANY_CREDENTIAL(id);
    END

