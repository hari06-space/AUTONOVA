CREATE TABLE MST_VENDOR_MASTER (
    ID BIGINT IDENTITY(1,1) PRIMARY KEY,
    REFERENCE_CODE NVARCHAR(10),
    VENDOR_NAME NVARCHAR(100),
    SHORT_NAME NVARCHAR(25),
    PRINT_NAME NVARCHAR(150),
    ADDRESS NVARCHAR(300),
    CITY NVARCHAR(50),
    STATE NVARCHAR(50),
    COUNTRY NVARCHAR(50),
    PIN_CODE NVARCHAR(20),
    STATE_CODE INT,
    LOCATION NVARCHAR(300),
    DISTANCE INT,
    IS_CUSTOMER BIT DEFAULT 0,
    IS_SUPPLIER BIT DEFAULT 0,
    IS_SUBCON BIT DEFAULT 0,
    GSTIN NVARCHAR(15),
    PAN_NO NVARCHAR(15),
    SEGMENT NVARCHAR(50),
    SUB_SEGMENT NVARCHAR(50),
    DOMAIN_NAME NVARCHAR(100),
    REGISTER_NO NVARCHAR(50),
    CIN_NO NVARCHAR(50),
    ISO_NUMBER NVARCHAR(50),
    WEBSITE NVARCHAR(30),
    DAILY_DISPATCH_MAIL NVARCHAR(30),
    CURRENCY_CODE NVARCHAR(10),
    DISPATCH_MODE NVARCHAR(50),
    PAYMENT_TERMS NVARCHAR(50),
    DELIVERY_TERMS NVARCHAR(50),
    ISO_EXPIRY_DATE DATE,
    NDA_REQUIRED BIT DEFAULT 0,
    NEGOTIATE_REQUIRED BIT DEFAULT 0,
    DAILY_MAIL_REQUIRED BIT DEFAULT 0,
    LD_APPLICABLE BIT DEFAULT 0,
    PRIME_VENDOR BIT DEFAULT 0,
    FRIEGHT_APPLICABLE BIT DEFAULT 0,
    IS_ACTIVE BIT DEFAULT 1,
    CREATED_BY NVARCHAR(50) NOT NULL,
    CREATED_DATE DATETIME DEFAULT GETDATE(),
    UPDATED_BY NVARCHAR(50),
    UPDATED_DATE DATETIME
);
