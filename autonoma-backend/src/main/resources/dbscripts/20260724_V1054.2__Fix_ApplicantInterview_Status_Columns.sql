    OPEN ix; FETCH NEXT FROM ix INTO @nm; WHILE @@FETCH_STATUS=0 BEGIN SET @sql='DROP INDEX '+QUOTENAME(@nm)+' ON HR_APPLICANT_INTERVIEW'; EXEC(@sql); FETCH NEXT FROM ix INTO @nm; END CLOSE ix; DEALLOCATE ix;
    DECLARE dc CURSOR FOR SELECT dc.name FROM sys.default_constraints dc JOIN sys.columns c ON dc.parent_column_id=c.column_id AND dc.parent_object_id=c.object_id WHERE c.object_id=OBJECT_ID('HR_APPLICANT_INTERVIEW') AND c.name='INTERVIEW_STATUS';
