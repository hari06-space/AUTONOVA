-- Fix: Migrate HR_APPLICANT_INTERVIEW INTERVIEW_STATUS and INTERVIEW_RESULT
-- from NVARCHAR to BIGINT FK referencing AD_STATUS_MASTER
-- Values: PENDING, REJECTED, SELECTED, PASS, FAIL
-- =============================================================================
SET NOCOUNT ON;

-- Ensure all required statuses exist
IF NOT EXISTS (SELECT 1 FROM AD_STATUS_MASTER WHERE UPPER(TRIM(NAME))='PASS') INSERT INTO AD_STATUS_MASTER(NAME) VALUES('PASS');
IF NOT EXISTS (SELECT 1 FROM AD_STATUS_MASTER WHERE UPPER(TRIM(NAME))='FAIL') INSERT INTO AD_STATUS_MASTER(NAME) VALUES('FAIL');
IF NOT EXISTS (SELECT 1 FROM AD_STATUS_MASTER WHERE UPPER(TRIM(NAME))='PENDING') INSERT INTO AD_STATUS_MASTER(NAME) VALUES('PENDING');
IF NOT EXISTS (SELECT 1 FROM AD_STATUS_MASTER WHERE UPPER(TRIM(NAME))='SELECTED') INSERT INTO AD_STATUS_MASTER(NAME) VALUES('SELECTED');
