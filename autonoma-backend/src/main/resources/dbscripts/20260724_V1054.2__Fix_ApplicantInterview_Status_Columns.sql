    EXEC('UPDATE HR_APPLICANT_INTERVIEW SET INTERVIEW_STATUS_ID = (SELECT ID FROM AD_STATUS_MASTER WHERE UPPER(TRIM(NAME)) = UPPER(TRIM(INTERVIEW_STATUS))) WHERE INTERVIEW_STATUS IS NOT NULL');
    DECLARE @sql NVARCHAR(512); DECLARE @nm NVARCHAR(256);
