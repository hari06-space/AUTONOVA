-- ---- INTERVIEW_STATUS ----
IF EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='HR_APPLICANT_INTERVIEW' AND COLUMN_NAME='INTERVIEW_STATUS' AND DATA_TYPE IN ('nvarchar','varchar'))
BEGIN
