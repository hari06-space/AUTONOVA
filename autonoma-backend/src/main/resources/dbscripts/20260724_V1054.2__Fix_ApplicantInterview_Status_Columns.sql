    EXEC('ALTER TABLE HR_APPLICANT_INTERVIEW DROP COLUMN INTERVIEW_STATUS');
    EXEC('EXEC sp_rename ''HR_APPLICANT_INTERVIEW.INTERVIEW_STATUS_ID'', ''INTERVIEW_STATUS'', ''COLUMN''');
    PRINT 'Migrated HR_APPLICANT_INTERVIEW.INTERVIEW_STATUS';
END

GO

