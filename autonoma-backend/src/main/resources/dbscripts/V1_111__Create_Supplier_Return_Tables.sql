('Wrong Item', 'Incorrect item supplied', 'SYSTEM', GETDATE()),
('Wrong Quantity', 'Quantity mismatch', 'SYSTEM', GETDATE()),
('Quality Issue', 'Failed quality checks after acceptance', 'SYSTEM', GETDATE()),
('IQC Rejected', 'Failed initial quality control', 'SYSTEM', GETDATE()),
('Specification Mismatch', 'Did not match PO specs', 'SYSTEM', GETDATE()),
('Supplier Recall', 'Recalled by supplier', 'SYSTEM', GETDATE()),
('Excess Supply', 'Over-supplied quantity', 'SYSTEM', GETDATE()),
