-- 3. Create Performance Indexes on AD_USER_SESSION_AUDIT
IF NOT EXISTS (
    SELECT 1 FROM sys.indexes 
    WHERE name = N'IX_AD_USER_SESSION_USER_STATUS' 
      AND object_id = OBJECT_ID(N'[dbo].[AD_USER_SESSION_AUDIT]')
)
BEGIN
    CREATE NONCLUSTERED INDEX [IX_AD_USER_SESSION_USER_STATUS]
    ON [dbo].[AD_USER_SESSION_AUDIT] ([USER_ID], [SESSION_STATUS])
    INCLUDE ([SESSION_ID], [LOGIN_TIME], [LAST_ACTIVITY], [DEVICE_NAME], [IP_ADDRESS]);
    PRINT 'Created index IX_AD_USER_SESSION_USER_STATUS.';
END;

