-- 1. Add SINGLE_ACTIVE_SESSION column to AD_COMPANY_CREDENTIAL
IF NOT EXISTS (
    SELECT 1 
    FROM sys.columns 
    WHERE object_id = OBJECT_ID(N'[dbo].[AD_COMPANY_CREDENTIAL]') 
      AND name = N'SINGLE_ACTIVE_SESSION'
)
BEGIN
    ALTER TABLE [dbo].[AD_COMPANY_CREDENTIAL]
    ADD [SINGLE_ACTIVE_SESSION] BIT NOT NULL CONSTRAINT DF_AD_COMPANY_CREDENTIAL_SINGLE_ACTIVE_SESSION DEFAULT 0;
    PRINT 'Added SINGLE_ACTIVE_SESSION column to AD_COMPANY_CREDENTIAL.';
END;

