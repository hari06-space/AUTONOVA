    END;

    ALTER TABLE HR_LEAVE_TRAVEL_DETAILS DROP COLUMN IS_ACTIVE;
    PRINT 'Dropped IS_ACTIVE column from HR_LEAVE_TRAVEL_DETAILS.';
END;

-- Step 5: Drop UPDATED_BY and UPDATED_DATE columns
IF OBJECT_ID('dbo.HR_LEAVE_TRAVEL_DETAILS', 'U') IS NOT NULL AND EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'HR_LEAVE_TRAVEL_DETAILS' AND COLUMN_NAME = 'UPDATED_BY')
