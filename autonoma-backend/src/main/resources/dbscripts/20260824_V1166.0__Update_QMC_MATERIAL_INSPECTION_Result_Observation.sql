IF NOT EXISTS (
    SELECT 1 FROM sys.columns 
    WHERE Name = N'OBSERVATION' 
    AND Object_ID = Object_ID(N'QMC_MATERIAL_INSPECTION')
)
BEGIN
    -- Add OBSERVATION column to store JSON data
    ALTER TABLE QMC_MATERIAL_INSPECTION ADD OBSERVATION NVARCHAR(MAX);
END
GO

-- Migrate existing JSON data from RESULT to OBSERVATION
UPDATE QMC_MATERIAL_INSPECTION 
SET OBSERVATION = RESULT 
WHERE RESULT IS NOT NULL AND OBSERVATION IS NULL;
GO

-- Set RESULT to NULL after migration
UPDATE QMC_MATERIAL_INSPECTION 
SET RESULT = NULL 
WHERE RESULT IS NOT NULL;
GO

IF EXISTS (
    SELECT 1 FROM sys.columns 
    WHERE Name = N'RESULT' 
    AND Object_ID = Object_ID(N'QMC_MATERIAL_INSPECTION')
)
BEGIN
    -- Change RESULT column type to store simple text inputs
    ALTER TABLE QMC_MATERIAL_INSPECTION ALTER COLUMN RESULT NVARCHAR(100);
END
GO
