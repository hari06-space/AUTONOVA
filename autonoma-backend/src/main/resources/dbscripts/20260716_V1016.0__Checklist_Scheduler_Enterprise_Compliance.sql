-- IDEMPOTENT DB MIGRATION: Checklist Scheduler Enterprise Compliance

-- 1. Add HOLIDAY_STRATEGY to SCHEDULE_CONFIGURATION
IF NOT EXISTS (SELECT * FROM sys.columns WHERE object_id = OBJECT_ID('SCHEDULE_CONFIGURATION') AND name = 'HOLIDAY_STRATEGY')
BEGIN
    ALTER TABLE SCHEDULE_CONFIGURATION ADD HOLIDAY_STRATEGY VARCHAR(20) DEFAULT 'NEXT';
END;

-- 2. Add ADDITIONAL_EMPLOYEE_IDS to QMS_CHECKLIST_MASTER
IF NOT EXISTS (SELECT * FROM sys.columns WHERE object_id = OBJECT_ID('QMS_CHECKLIST_MASTER') AND name = 'ADDITIONAL_EMPLOYEE_IDS')
BEGIN
    ALTER TABLE QMS_CHECKLIST_MASTER ADD ADDITIONAL_EMPLOYEE_IDS VARCHAR(1000);
END;

-- 3. Add columns to QMS_CHECKLIST_ASSIGNMENT
IF NOT EXISTS (SELECT * FROM sys.columns WHERE object_id = OBJECT_ID('QMS_CHECKLIST_ASSIGNMENT') AND name = 'EXECUTION_TYPE')
