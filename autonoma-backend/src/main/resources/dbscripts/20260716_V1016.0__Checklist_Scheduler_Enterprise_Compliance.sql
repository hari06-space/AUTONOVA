IF NOT EXISTS (SELECT * FROM sys.columns WHERE object_id = OBJECT_ID('QMS_CHECKLIST_CLOSED') AND name = 'SCHEDULER_NAME')
BEGIN
    ALTER TABLE QMS_CHECKLIST_CLOSED ADD SCHEDULER_NAME VARCHAR(100);
