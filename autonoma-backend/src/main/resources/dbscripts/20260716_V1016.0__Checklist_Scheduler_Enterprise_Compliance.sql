    ALTER TABLE QMS_CHECKLIST_ASSIGNMENT ADD SCHEDULER_NAME VARCHAR(100);
END;

IF NOT EXISTS (SELECT * FROM sys.columns WHERE object_id = OBJECT_ID('QMS_CHECKLIST_ASSIGNMENT') AND name = 'TRIGGER_ID')
BEGIN
    ALTER TABLE QMS_CHECKLIST_ASSIGNMENT ADD TRIGGER_ID BIGINT;
END;

IF NOT EXISTS (SELECT * FROM sys.columns WHERE object_id = OBJECT_ID('QMS_CHECKLIST_ASSIGNMENT') AND name = 'DUE_DATE')
BEGIN
    ALTER TABLE QMS_CHECKLIST_ASSIGNMENT ADD DUE_DATE DATE;
END;

-- 4. Add columns to QMS_CHECKLIST_CLOSED
IF NOT EXISTS (SELECT * FROM sys.columns WHERE object_id = OBJECT_ID('QMS_CHECKLIST_CLOSED') AND name = 'EXECUTION_TYPE')
