    ALTER TABLE QMS_CHECKLIST_ASSIGNMENT ADD EXECUTION_TYPE VARCHAR(10) DEFAULT 'AUTO';
END;

IF NOT EXISTS (SELECT * FROM sys.columns WHERE object_id = OBJECT_ID('QMS_CHECKLIST_ASSIGNMENT') AND name = 'SCHEDULER_NAME')
