IF NOT EXISTS (SELECT * FROM sys.columns WHERE object_id = OBJECT_ID('QMS_CHECKLIST_CLOSED') AND name = 'DUE_DATE')
BEGIN
    ALTER TABLE QMS_CHECKLIST_CLOSED ADD DUE_DATE DATE;
END;

-- 5. Create QMS_SCHEDULER_EXECUTION_LOG table
IF OBJECT_ID('QMS_SCHEDULER_EXECUTION_LOG', 'U') IS NULL
BEGIN
    CREATE TABLE QMS_SCHEDULER_EXECUTION_LOG (
        ID BIGINT IDENTITY(1,1) PRIMARY KEY,
        SCHEDULER_NAME VARCHAR(100) NOT NULL,
        EXECUTION_TYPE VARCHAR(10) NOT NULL,
        TRIGGER_TIME DATETIME NOT NULL,
        START_TIME DATETIME NOT NULL,
        END_TIME DATETIME NOT NULL,
        DURATION_MS BIGINT,
        SUCCESS_COUNT INT DEFAULT 0,
        FAILED_COUNT INT DEFAULT 0,
        SKIPPED_COUNT INT DEFAULT 0,
        STATUS VARCHAR(20) NOT NULL,
        REASON VARCHAR(500),
        MACHINE_NAME VARCHAR(100),
        IP_ADDRESS VARCHAR(50),
        APP_VERSION VARCHAR(20)
    );
END;

-- 6. Backfill existing configurations
IF EXISTS (SELECT * FROM sys.columns WHERE object_id = OBJECT_ID('SCHEDULE_CONFIGURATION') AND name = 'HOLIDAY_STRATEGY')
BEGIN
    EXEC('UPDATE SCHEDULE_CONFIGURATION SET HOLIDAY_STRATEGY = ''NEXT'' WHERE HOLIDAY_STRATEGY IS NULL');
END;
