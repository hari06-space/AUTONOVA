CREATE TABLE QMS_AUDIT_SCHEDULER_CONFIG (
    ID BIGINT IDENTITY(1,1) PRIMARY KEY,
    CONFIG_CODE NVARCHAR(50) NOT NULL UNIQUE,
    CONFIG_NAME NVARCHAR(255) NOT NULL,
    AUDIT_TYPE_ID BIGINT,
    DEPARTMENT_ID BIGINT,
    AUDIT_AREA_ID BIGINT,
    FREQUENCY NVARCHAR(50) NOT NULL,
    REPEAT_EVERY_VALUE INT,
    REPEAT_EVERY_UNIT NVARCHAR(50),
    WEEK_DAYS NVARCHAR(255),
    START_TIME NVARCHAR(50) NOT NULL,
    END_TIME NVARCHAR(50) NOT NULL,
    STATUS BIT,
    CRITERIA_MIN_COUNT INT,
    HOLIDAY_STRATEGY NVARCHAR(50) DEFAULT 'NEXT',
    LEAVE_VALIDATION BIT DEFAULT 1,
    DUPLICATE_CHECK BIT DEFAULT 1,
    CREATED_BY NVARCHAR(50),
    CREATED_DATE DATETIME,
    UPDATED_BY NVARCHAR(50),
    UPDATED_DATE DATETIME,
    CONSTRAINT FK_QMS_AUDIT_SCHEDULER_CONFIG_AUDIT_TYPE FOREIGN KEY (AUDIT_TYPE_ID) REFERENCES QMS_AUDIT_TYPE(ID),
    CONSTRAINT FK_QMS_AUDIT_SCHEDULER_CONFIG_DEPARTMENT FOREIGN KEY (DEPARTMENT_ID) REFERENCES HR_DEPARTMENT(ID),
    CONSTRAINT FK_QMS_AUDIT_SCHEDULER_CONFIG_AUDIT_AREA FOREIGN KEY (AUDIT_AREA_ID) REFERENCES QMS_AUDIT_AREA(ID),
    CONSTRAINT FK_QMS_AUDIT_SCHEDULER_CONFIG_CREATED_BY FOREIGN KEY (CREATED_BY) REFERENCES AD_USER_CREDENTIAL(USER_ID),
    CONSTRAINT FK_QMS_AUDIT_SCHEDULER_CONFIG_UPDATED_BY FOREIGN KEY (UPDATED_BY) REFERENCES AD_USER_CREDENTIAL(USER_ID)
);
