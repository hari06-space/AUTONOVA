    @Transactional(readOnly = true)
    public SmartRepliesResponse getSmartReplies(Long channelId) {
        List<CommMessage> msgs = messageRepository.findByChannelIdOrderByIdAsc(channelId);
        List<String> suggestions = new ArrayList<>();
        if (msgs.isEmpty()) {
            suggestions.add("Hello team!");
            suggestions.add("Let me know when you're available.");
            suggestions.add("Acknowledged.");
        } else {
            CommMessage lastMsg = msgs.get(msgs.size() - 1);
            String text = (lastMsg.getMessageContent() != null ? lastMsg.getMessageContent() : "").toLowerCase();
            if (text.contains("when") || text.contains("time") || text.contains("schedule")) {
                suggestions.add("Let's sync at 3 PM today.");
                suggestions.add("I have shared the schedule in QMS.");
                suggestions.add("Checking my calendar now.");
            } else if (text.contains("status") || text.contains("update") || text.contains("done")) {
                suggestions.add("The review is complete and updated.");
                suggestions.add("Working on the final report now.");
                suggestions.add("Will send the update shortly.");
            } else if (text.contains("check") || text.contains("verify") || text.contains("audit")) {
                suggestions.add("Checked and verified.");
                suggestions.add("No non-conformances observed.");
                suggestions.add("Need additional evidence for Clause 8.");
            } else {
                suggestions.add("Acknowledged with thanks.");
                suggestions.add("Sounds good, proceeding.");
                suggestions.add("Let me verify and get back to you.");
            }
        }
        return SmartRepliesResponse.builder()
                .suggestions(suggestions)
                .build();
    }

    // --- HELPERS ---
    private List<MemberInfo> getChannelMembersInfo(Long channelId) {
        List<CommChannelMember> members = memberRepository.findByChannelId(channelId);
        return members.stream()
                .map(m -> getUserInfo(m.getUserId()))
                .collect(Collectors.toList());
    }

    private MemberInfo getUserInfo(String userId) {
        Optional<UserCredential> userOpt = userRepository.findByUserId(userId);
        if (!userOpt.isPresent()) {
            return MemberInfo.builder()
                    .userId(userId)
                    .employeeName(userId)
                    .isOnline(false)
                    .build();
        }

        UserCredential user = userOpt.get();
        String empName = userId;
        String empCode = null;
        Long empId = user.getEmpId();
        String deptName = "General Admin";
        String desName = "BOS Staff";
        String imgName = user.getImgName() != null ? user.getImgName() : "default_avatar.png";

        if (user.getEmpId() != null) {
            Optional<EmployeeMaster> empOpt = employeeRepository.findById(user.getEmpId());
            if (empOpt.isPresent()) {
                EmployeeMaster emp = empOpt.get();
                empCode = emp.getEmpCode();
                if (emp.getEmployeeName() != null && !emp.getEmployeeName().trim().isEmpty()) {
                    empName = emp.getEmployeeName();
                }
                if (emp.getDepartment() != null) {
                    deptName = emp.getDepartment().getDepartmentName();
                }
                if (emp.getDesignation() != null) {
                    desName = emp.getDesignation().getDesignationName();
                }
            }
        }

        // Fetch presence
        Optional<CommUserStatus> presenceOpt = statusRepository.findById(userId);
        boolean isOnline = presenceOpt.map(p -> p.getIsOnline() == 1).orElse(false);
        Date lastSeen = presenceOpt.map(CommUserStatus::getLastSeen).orElse(new Date());
        boolean isTyping = presenceOpt.map(p -> p.getIsTypingChannelId() != null).orElse(false);

        return MemberInfo.builder()
                .userId(userId)
                .empId(empId)
                .employeeCode(empCode)
                .employeeName(empName)
                .departmentName(deptName)
                .designationName(desName)
                .imgName(imgName)
                .isOnline(isOnline)
                .lastSeen(lastSeen)
                .isTyping(isTyping)
                .build();
    }

    private String getEmployeeName(String userId) {
        return userId; // Return BOS User ID directly to prevent collapsing
    }

    // --- DELETE CHANNEL ---
    @Transactional
    public void deleteChannel(Long channelId, String userId) {
        // Verify membership
        Optional<CommChannelMember> mem = memberRepository.findByChannelIdAndUserId(channelId, userId);
        if (mem.isPresent()) {
            // Delete channel entirely
            memberRepository.delete(mem.get());
            
            // If no members left or if it's a DIRECT channel, we might delete it completely
            List<CommChannelMember> remaining = memberRepository.findByChannelId(channelId);
            if (remaining.isEmpty() || channelRepository.findById(channelId).map(c -> "DIRECT".equals(c.getChannelType())).orElse(false)) {
                // For direct chats or empty groups, delete everything
                memberRepository.deleteAll(remaining);
                List<CommMessage> msgs = messageRepository.findByChannelIdOrderByIdAsc(channelId);
                messageRepository.deleteAll(msgs);
                channelRepository.deleteById(channelId);
            }
        }
    }
